#!/usr/bin/env python3
"""
Summarise the stored runs, written to outputs/summary.md:

- test metric, mean ± std over seeds, for each results folder (Tables 1, 3, 7, 9)
  and for the search-free rule (Table 10);
- tokenisation time from run_meta.json (Table 6);
- time per 1000 training steps and GPU memory from the benchmark (Tables 2, 5).

Standard deviations are population standard deviations over the seeds.

    python outputs/summarise_results.py
"""

import csv
import glob
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.abspath(__file__))

UEA = [
    ("EigenWorms", "EigenWorms"),
    ("SelfRegulationSCP1", "SCP1"),
    ("SelfRegulationSCP2", "SCP2"),
    ("EthanolConcentration", "Ethanol"),
    ("Heartbeat", "Heartbeat"),
    ("MotorImagery", "Motor"),
]

UEA_FOLDERS = [
    ("sig_mamba", "LogSig-SSM"),
    ("sig_mamba_depth1", "LogSig-SSM, depth 1"),
    ("sig_mamba_catch", "Catch24-Mamba"),
    ("sig_mamba_wst", "Wst-Mamba"),
    ("sig_s5", "LogSig-S5"),
    ("sig_transformers", "LogSig-Transformer"),
]

# (dataset folder, column label, scale, decimals)
OTHER = [
    ("ppg", "PPG-DaLiA (MSE ×10⁻²)", 100, 2),
    ("Weather", "Weather", 1, 3),
    ("physionet", "PhysioNet, OI (AUROC %)", 100, 2),
    ("physionet_no_oi", "PhysioNet, no OI (AUROC %)", 100, 2),
]

# Runs that log the tokenisation time (run_meta.json) for each dataset
TOKENISATION_RUNS = {
    "EigenWorms": "sig_mamba_efficiency",
    "SelfRegulationSCP1": "sig_mamba_efficiency",
    "SelfRegulationSCP2": "sig_mamba_efficiency",
    "EthanolConcentration": "sig_mamba",
    "Heartbeat": "sig_mamba",
    "MotorImagery": "sig_mamba",
}

BENCHMARK = os.path.join(ROOT, "sig_mamba_benchmark", "2026-10-03_rerun", "current_configs")


def test_metrics(folder, dataset):
    paths = sorted(glob.glob(os.path.join(ROOT, folder, dataset, "*", "test_metric.npy")))
    return np.array([float(np.asarray(np.load(p)).reshape(-1)[-1]) for p in paths])


def rule_metrics(dataset):
    with open(os.path.join(ROOT, "search_free_rule", "results.csv")) as f:
        rows = [r for r in csv.DictReader(f) if r["dataset"] == dataset and r["status"] == "ok"]
    return np.array([float(r["test_acc"]) for r in rows])


def cell(values, scale, decimals):
    if len(values) == 0:
        return "—"
    v = values * scale
    if len(v) == 1:
        return f"{v[0]:.{decimals}f}"
    return f"{v.mean():.{decimals}f} ± {v.std():.{decimals}f}"


def uea_row(label, folder, metrics):
    cells, means = [], []
    for ds, _ in UEA:
        v = metrics(ds)
        cells.append(cell(v, 100, 2))
        if len(v):
            means.append(v.mean() * 100)
    avg = f"{np.mean(means):.2f}" if len(means) == len(UEA) else "—"
    return f"| {label} | `{folder}` | " + " | ".join(cells) + f" | {avg} |"


def main():
    lines = ["# Results summary", "",
             "Generated by `python outputs/summarise_results.py` from the files in `outputs/`.", "",
             "## UEA classification accuracy (%), Tables 1, 7, 9 and 10", "",
             "Mean ± std over the five seeds.", "",
             "| Model | Folder | " + " | ".join(short for _, short in UEA) + " | Avg |",
             "|---|---|" + "---:|" * (len(UEA) + 1)]
    for folder, label in UEA_FOLDERS:
        lines.append(uea_row(label, folder, lambda ds, folder=folder: test_metrics(folder, ds)))
    lines.append(uea_row("LogSig-SSM, search-free rule", "search_free_rule", rule_metrics))

    lines += ["", "## LogSig-SSM on PPG-DaLiA, Weather and PhysioNet, Table 3", "",
              "| " + " | ".join(label for _, label, _, _ in OTHER) + " |",
              "|" + "---:|" * len(OTHER),
              "| " + " | ".join(cell(test_metrics("sig_mamba", ds), s, d) for ds, _, s, d in OTHER) + " |"]

    lines += ["", "## Tokenisation time, Table 6", "",
              "`logsig_precompute_s` in `run_meta.json`, mean ± std over the five seeds, and as a share of the",
              "summed `all_time.npy` of the same runs.", "",
              "| Dataset | Runs | Tokenisation (s) | % of one training run |",
              "|---|---|---:|---:|"]
    total = 0.0
    for ds, short in UEA:
        folder = TOKENISATION_RUNS[ds]
        runs = sorted(glob.glob(os.path.join(ROOT, folder, ds, "*", "run_meta.json")))
        tok = np.array([json.load(open(p))["logsig_precompute_s"] for p in runs])
        train = np.array([np.sum(np.load(os.path.join(os.path.dirname(p), "all_time.npy"))) for p in runs])
        total += tok.mean()
        lines.append(f"| {short} | `{folder}` | {tok.mean():.3f} ± {tok.std():.3f} | {100 * tok.mean() / train.mean():.1f} |")
    lines.append(f"| All six | | {total:.2f} | |")

    lines += ["", "## Time per 1000 training steps and GPU memory, Tables 2 and 5", "",
              "Current configurations on one RTX 4090 (`sig_mamba_benchmark/2026-10-03_rerun/current_configs/`),",
              "mean over the runs; see `sig_mamba_benchmark/README.md` for the protocol.", "",
              "| Dataset | Parameters | Time / 1000 steps (s) | Average reserved (MB) | Peak allocated (MB) |",
              "|---|---:|---:|---:|---:|"]
    bench = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(BENCHMARK, "*.json")))]
    for ds, short in UEA:
        rs = [r for b in bench for r in b["results"] if r["dataset"] == ds]
        lines.append(f"| {short} | {rs[0]['num_params']:,} | {np.mean([r['runtime_s_1000'] for r in rs]):.2f} | "
                     f"{np.mean([r['avg_reserved_mb'] for r in rs]):.0f} | {np.mean([r['peak_alloc_mb'] for r in rs]):.0f} |")

    text = "\n".join(lines) + "\n"
    with open(os.path.join(ROOT, "summary.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
